# frozen_string_literal: true

module Whop_sdk
  module Media
    class Client
      # @param client [Whop_sdk::Internal::Http::RawClient]
      #
      # @return [void]
      def initialize(client:)
        @client = client
      end

      # Starts an AI media generation job billed from the account's balance. Generation is asynchronous — poll `GET
      # /media/{id}` until the asset is `ready`, then use `file.id` anywhere attachments are accepted.
      #
      # @param request_options [Hash]
      # @param params [Whop_sdk::Media::Types::GenerateMediaRequest]
      # @option request_options [String] :base_url
      # @option request_options [Hash{String => Object}] :additional_headers
      # @option request_options [Hash{String => Object}] :additional_query_parameters
      # @option request_options [Hash{String => Object}] :additional_body_parameters
      # @option request_options [Integer] :timeout_in_seconds
      #
      # @example
      #   client.media.generate(
      #     prompt: "A 9:16 product showcase of a cordless power scrubber",
      #     type: "video"
      #   )
      #
      # @return [Whop_sdk::Types::MediaAsset]
      def generate(request_options: {}, **params)
        params = Whop_sdk::Internal::Types::Utils.normalize_keys(params)
        request = Whop_sdk::Internal::JSON::Request.new(
          base_url: request_options[:base_url],
          method: "POST",
          path: "media/generate",
          body: Whop_sdk::Media::Types::GenerateMediaRequest.new(params).to_h,
          request_options: request_options
        )
        begin
          response = @client.send(request)
        rescue Net::HTTPRequestTimeout
          raise Whop_sdk::Errors::TimeoutError
        end
        code = response.code.to_i
        if code.between?(200, 299)
          Whop_sdk::Types::MediaAsset.load(response.body)
        else
          error_class = Whop_sdk::Errors::ResponseError.subclass_for_code(code)
          raise error_class.new(response.body, code: code)
        end
      end

